import type { LucideIcon } from 'lucide-react';
import {
  Flag,
  Pointer,
  Mail,
  Zap,
  ArrowRight,
  ArrowLeft,
  ArrowUp,
  ArrowDown,
  RotateCw,
  RotateCcw,
  ChevronsUp,
  House,
  MessageCircle,
  Plus,
  Minus,
  Scaling,
  Eye,
  EyeOff,
  Volume2,
  Mic,
  Clock,
  Repeat,
  Gauge,
  Square,
  Infinity as InfinityIcon,
  BookOpen,
} from 'lucide-react';

const map: Record<string, LucideIcon> = {
  bandeira: Flag,
  toque: Pointer,
  mensagem: Mail,
  colisao: Zap,
  'mover-direita': ArrowRight,
  'mover-esquerda': ArrowLeft,
  'mover-cima': ArrowUp,
  'mover-baixo': ArrowDown,
  'girar-horario': RotateCw,
  'girar-antihorario': RotateCcw,
  pular: ChevronsUp,
  inicio: House,
  dizer: MessageCircle,
  crescer: Plus,
  diminuir: Minus,
  'tamanho-normal': Scaling,
  esconder: EyeOff,
  mostrar: Eye,
  pop: Volume2,
  gravar: Mic,
  esperar: Clock,
  repetir: Repeat,
  velocidade: Gauge,
  fim: Square,
  'repetir-sempre': InfinityIcon,
  'ir-pagina': BookOpen,
};

export function blocoIcon(id: string): LucideIcon {
  return map[id] ?? Square;
}